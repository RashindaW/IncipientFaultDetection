"""
PRONTO Merged Dataset for PyTorch Geometric (15 Variables)

Loads PRONTO benchmark data from preprocessed merged CSV files with 15 variables:
- 4 conditioning variables: Air In, Water In, Air T, Water T
- 11 measurement variables: same as DyEdgeGAT

This loader uses the fault-type CSV files generated by convert_merged_to_15var.py.
"""
from __future__ import annotations

import numpy as np
import pandas as pd
import torch
from torch_geometric.data import Data, Dataset
from pathlib import Path
from typing import List, Optional, Tuple

from .pronto_merged_config import (
    PRONTO_15_COLUMNS,
    CONDITIONING_VARS,
    MEASUREMENT_VARS,
    CONDITIONING_INDICES,
    MEASUREMENT_INDICES,
)


class PRONTOMergedDataset(Dataset):
    """
    Dataset for PRONTO benchmark using preprocessed merged CSV files (15 variables).

    Loads data from fault-type CSV files where:
    - Air/Water flow rates are pre-combined
    - Alarm features are excluded
    - Data is already split by fault type

    Variable Classification:
    - Conditioning variables (4): Air In, Water In, Air T, Water T
    - Measurement variables (11): Air P, Mixture zone P, riser outlet P, etc.

    Key features:
    - Loads from fault-type CSV files (normal, slugging, air_blockage, etc.)
    - Proper windowing with temporal boundaries
    - Support for train/val/test splits
    - Per-split normalization to avoid data leakage
    - Segment shuffle mode to address temporal drift in normal data

    Split Modes:
    - 'temporal': Traditional time-ordered splits (70/30 normal for train/val)
    - 'segment_shuffle': Segments of normal data shuffled to balance operating conditions
      across train/val/test splits (addresses severe temporal drift in the data)

    Returns Data objects with:
    - x: Measurements [n_measurement_vars=11, window_size]
    - c: Conditioning [n_conditioning_vars=4, window_size]
    - edge_index: Fully connected graph edges [2, n_edges]
    - y: Fault label (always 0 in merged data)
    - y_future: Future measurements (if pred_horizon > 0)
    """

    def __init__(
        self,
        data_dir: str,
        split: str,
        window_size: int = 15,
        stride: int = 1,
        normalize: bool = True,
        normalization_stats: Optional[Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]] = None,
        require_stats: bool = False,
        pred_horizon: int = 0,
        split_mode: str = 'temporal',
        n_segments: int = 10,
        split_ratios: Tuple[float, float, float] = (0.7, 0.2, 0.1),
        random_seed: int = 42,
        shuffle_windows: bool = True,
        train_segments: Optional[List[int]] = None,
        val_segments: Optional[List[int]] = None,
        test_segments: Optional[List[int]] = None,
    ):
        """
        Initialize PRONTO merged dataset.

        Args:
            data_dir: Path to 15var_merged directory containing fault-type CSV files
            split: Data split name ('train', 'val', 'test', 'test_normal', or fault type name)
            window_size: Number of timesteps per window
            stride: Step size between consecutive windows
            normalize: Whether to normalize data
            normalization_stats: Pre-computed (X_mean, X_std, C_mean, C_std) for normalization
            require_stats: If True, raise error if normalization_stats is None
            pred_horizon: Number of future timesteps for prediction (0 = no prediction)
            split_mode: How to split data:
                - 'temporal': Traditional 70/30 temporal split
                - 'segment_shuffle': Shuffle segments to balance operating conditions
            n_segments: Number of segments for segment_shuffle mode (default: 10)
            split_ratios: Ratios for train/val/test when using segment_shuffle (default: 0.7/0.2/0.1)
            random_seed: Random seed for reproducibility
            shuffle_windows: Whether to shuffle windows within each split (default: True)
            train_segments: Explicit list of segment indices for training (overrides split_ratios)
            val_segments: Explicit list of segment indices for validation (overrides split_ratios)
            test_segments: Explicit list of segment indices for testing (overrides split_ratios)
        """
        super().__init__()
        self.data_dir = Path(data_dir)
        self.split = split
        self.fault_type = split  # Store for label assignment
        self.window_size = window_size
        self.stride = max(1, stride)
        self.normalize = normalize
        self.normalization_stats = normalization_stats
        self.require_stats = require_stats
        self.pred_horizon = max(0, int(pred_horizon))
        self.split_mode = split_mode
        self.n_segments = n_segments
        self.split_ratios = split_ratios
        self.random_seed = random_seed
        self.shuffle_windows = shuffle_windows
        self.train_segments = train_segments
        self.val_segments = val_segments
        self.test_segments = test_segments

        # Variable indices
        self.measurement_indices = np.array(MEASUREMENT_INDICES)
        self.conditioning_indices = np.array(CONDITIONING_INDICES)
        self.n_measurement_vars = len(MEASUREMENT_INDICES)
        self.n_conditioning_vars = len(CONDITIONING_INDICES)

        # Segment ranges for segment_shuffle mode (set during loading)
        self.segment_ranges = None

        # Load and preprocess data
        self.data, self.metadata = self._load_and_preprocess()
        self.windows = self._create_windows()

        print(f"PRONTO Merged Dataset [{split}] (mode={split_mode}): {len(self.windows)} windows")

    def _load_and_preprocess(self) -> Tuple[pd.DataFrame, dict]:
        """
        Load data from fault-type CSV files.

        For train/val splits in temporal mode, uses 70/30 split of normal data.
        For segment_shuffle mode, divides normal data into segments and shuffles
        them to balance operating conditions across splits.

        Returns:
            DataFrame with 15 columns and metadata dict
        """
        # Check if this is a segment_shuffle split (train/val/test_normal)
        if self.split_mode == 'segment_shuffle' and self.split in ('train', 'val', 'test_normal'):
            return self._load_segment_shuffle_mode()

        # Map split to fault type files and ranges (temporal mode)
        # Format: (filename, start_ratio, end_ratio)
        split_config = {
            'normal': [('normal.csv', 0.0, 1.0)],
            'slugging': [('slugging.csv', 0.0, 1.0)],
            'air_blockage': [('air_blockage.csv', 0.0, 1.0)],
            'air_leakage': [('air_leakage.csv', 0.0, 1.0)],
            'diverted_flow': [('diverted_flow.csv', 0.0, 1.0)],
            # Train: 70% of Normal only (removed air_blockage - fault data shouldn't be in training)
            'train': [
                ('normal.csv', 0.0, 0.7),
            ],
            # Val: 30% of Normal
            'val': [
                ('normal.csv', 0.7, 1.0),
            ],
            # test_normal: All normal data for baseline comparison
            'test_normal': [
                ('normal.csv', 0.0, 1.0),
            ],
            # Test: All fault types
            'test': [
                ('normal.csv', 0.0, 1.0),
                ('slugging.csv', 0.0, 1.0),
                ('air_blockage.csv', 0.0, 1.0),
                ('air_leakage.csv', 0.0, 1.0),
                ('diverted_flow.csv', 0.0, 1.0),
            ],
        }

        if self.split not in split_config:
            raise ValueError(f"Unknown split: {self.split}. Available: {list(split_config.keys())}")

        # Load all files for this split
        dfs = []
        for filename, start_ratio, end_ratio in split_config[self.split]:
            file_path = self.data_dir / filename
            if not file_path.exists():
                raise FileNotFoundError(f"File not found: {file_path}")

            df = pd.read_csv(file_path)

            # Validate columns
            if list(df.columns) != PRONTO_15_COLUMNS:
                raise ValueError(f"Column mismatch in {filename}. Expected {PRONTO_15_COLUMNS}")

            # Apply ratio filtering if needed
            if start_ratio > 0.0 or end_ratio < 1.0:
                n_total = len(df)
                start_idx = int(n_total * start_ratio)
                end_idx = int(n_total * end_ratio)
                df = df.iloc[start_idx:end_idx].reset_index(drop=True)
                print(f"  {filename}: Using rows {start_idx}:{end_idx} ({len(df)} / {n_total})")

            dfs.append(df)

        # Concatenate all data
        data = pd.concat(dfs, ignore_index=True)

        # Handle missing values (forward fill then backward fill)
        data = data.ffill().bfill()

        # Replace inf with large finite values
        data = data.replace([np.inf, -np.inf], np.nan)
        data = data.fillna(data.mean())

        metadata = {
            'n_timesteps': len(data),
            'n_files': len(dfs),
            'files': [f"{filename} [{start_ratio:.1f}-{end_ratio:.1f}]"
                     for filename, start_ratio, end_ratio in split_config[self.split]],
        }

        return data, metadata

    def _load_segment_shuffle_mode(self) -> Tuple[pd.DataFrame, dict]:
        """
        Load data using segment shuffle mode for balanced operating conditions.

        This addresses severe temporal drift in normal.csv where operating conditions
        change dramatically over time (e.g., Water In: +887%, Water Valve: +841%).

        Strategy:
        1. Divide normal.csv into equal segments
        2. Shuffle segment indices with random seed
        3. Assign segments to train/val/test_normal splits
        4. Windows created WITHIN segments to maintain temporal coherence

        Returns:
            DataFrame with 15 columns and metadata dict
        """
        # Load full normal.csv
        file_path = self.data_dir / 'normal.csv'
        if not file_path.exists():
            raise FileNotFoundError(f"File not found: {file_path}")

        all_data = pd.read_csv(file_path)

        # Validate columns
        if list(all_data.columns) != PRONTO_15_COLUMNS:
            raise ValueError(f"Column mismatch in normal.csv. Expected {PRONTO_15_COLUMNS}")

        n_rows = len(all_data)

        # Step 1: Create equal segments
        segment_size = n_rows // self.n_segments
        segment_ranges = []
        for i in range(self.n_segments):
            start = i * segment_size
            end = (i + 1) * segment_size if i < self.n_segments - 1 else n_rows
            segment_ranges.append((start, end))

        # Step 2: Assign segments to splits
        if self.train_segments is not None and self.val_segments is not None and self.test_segments is not None:
            # Use explicit segment assignments
            train_seg_indices = np.array(self.train_segments)
            val_seg_indices = np.array(self.val_segments)
            test_seg_indices = np.array(self.test_segments)

            # Validate no overlap and all segments covered
            all_assigned = set(train_seg_indices) | set(val_seg_indices) | set(test_seg_indices)
            all_segments = set(range(self.n_segments))
            if all_assigned != all_segments:
                missing = all_segments - all_assigned
                extra = all_assigned - all_segments
                raise ValueError(
                    f"Segment assignment mismatch. Missing: {missing}, Extra: {extra}. "
                    f"Expected segments 0-{self.n_segments-1}"
                )

            print(f"  Segment shuffle mode (explicit assignment, n_segments={self.n_segments}):")
        else:
            # Shuffle segment indices and assign by ratios
            rng = np.random.RandomState(self.random_seed)
            shuffled_indices = rng.permutation(self.n_segments)

            # Calculate number of segments per split
            n_train = int(self.n_segments * self.split_ratios[0])
            n_val = max(1, int(self.n_segments * self.split_ratios[1]))
            # Remaining go to test_normal
            n_test = self.n_segments - n_train - n_val

            train_seg_indices = shuffled_indices[:n_train]
            val_seg_indices = shuffled_indices[n_train:n_train + n_val]
            test_seg_indices = shuffled_indices[n_train + n_val:]

            print(f"  Segment shuffle mode (seed={self.random_seed}, n_segments={self.n_segments}):")

        print(f"    Train segments ({len(train_seg_indices)}): {sorted(train_seg_indices.tolist())}")
        print(f"    Val segments ({len(val_seg_indices)}): {sorted(val_seg_indices.tolist())}")
        print(f"    Test segments ({len(test_seg_indices)}): {sorted(test_seg_indices.tolist())}")

        # Step 3: Get segment ranges for this split
        if self.split == 'train':
            my_seg_indices = train_seg_indices
        elif self.split == 'val':
            my_seg_indices = val_seg_indices
        else:  # 'test_normal'
            my_seg_indices = test_seg_indices

        # Store segment ranges for window creation
        self.segment_ranges = [segment_ranges[i] for i in my_seg_indices]

        # Calculate total rows for this split
        total_rows = sum(end - start for start, end in self.segment_ranges)

        # Handle missing values
        all_data = all_data.ffill().bfill()
        all_data = all_data.replace([np.inf, -np.inf], np.nan)
        all_data = all_data.fillna(all_data.mean())

        metadata = {
            'n_timesteps': total_rows,
            'n_segments': len(my_seg_indices),
            'segment_indices': my_seg_indices.tolist(),
            'segment_ranges': self.segment_ranges,
            'split_mode': 'segment_shuffle',
        }

        return all_data, metadata

    def _create_windows(self) -> List[Tuple[int, int]]:
        """
        Create sliding windows over the dataset.

        For segment_shuffle mode, windows are created WITHIN each segment to
        maintain temporal coherence. For temporal mode, windows span the entire
        dataset continuously.

        Returns:
            List of (start_idx, end_idx) tuples for each window
        """
        windows = []
        required_length = self.window_size + self.pred_horizon

        if self.segment_ranges is not None:
            # Segment shuffle mode: create windows within each segment
            for seg_start, seg_end in self.segment_ranges:
                seg_length = seg_end - seg_start
                if seg_length < required_length:
                    print(f"  Warning: Segment [{seg_start}:{seg_end}] too short "
                          f"({seg_length} < {required_length}), skipping")
                    continue
                # Create windows within this segment only
                for offset in range(0, seg_length - required_length + 1, self.stride):
                    win_start = seg_start + offset
                    win_end = win_start + required_length
                    windows.append((win_start, win_end))

            # Shuffle windows within this split if enabled
            if self.shuffle_windows and windows:
                # Use a seed that's different for each split to ensure reproducibility
                split_seed = self.random_seed + hash(self.split) % (2**31)
                rng = np.random.RandomState(split_seed)
                rng.shuffle(windows)
        else:
            # Temporal mode: create windows over entire dataset
            n_timesteps = len(self.data)
            for start_idx in range(0, n_timesteps - required_length + 1, self.stride):
                end_idx = start_idx + required_length
                windows.append((start_idx, end_idx))

        return windows

    def compute_normalization_stats(self) -> Tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
        """
        Compute mean and std for measurements and conditioning variables.

        For segment_shuffle mode, only uses data from training segments.
        For temporal mode, uses all data in the split.

        Returns:
            (X_mean, X_std, C_mean, C_std) as numpy arrays
        """
        if self.segment_ranges is not None:
            # Segment shuffle mode: only use data from assigned segments
            segment_data = []
            for seg_start, seg_end in self.segment_ranges:
                segment_data.append(self.data.iloc[seg_start:seg_end])
            data_for_stats = pd.concat(segment_data, ignore_index=True)
        else:
            # Temporal mode: use all data in the split
            data_for_stats = self.data

        # Extract measurement and conditioning data
        X = data_for_stats.iloc[:, self.measurement_indices].values
        C = data_for_stats.iloc[:, self.conditioning_indices].values

        # Compute statistics
        X_mean = X.mean(axis=0)
        X_std = X.std(axis=0) + 1e-8  # Add small epsilon to avoid division by zero
        C_mean = C.mean(axis=0)
        C_std = C.std(axis=0) + 1e-8

        return X_mean, X_std, C_mean, C_std

    def _normalize_data(self, X: np.ndarray, C: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
        """
        Normalize measurement and conditioning variables.

        Args:
            X: Measurement variables [T, n_measurement_vars]
            C: Conditioning variables [T, n_conditioning_vars]

        Returns:
            Normalized (X, C)
        """
        if self.normalization_stats is None:
            if self.require_stats:
                raise ValueError("Normalization stats required but not provided")
            # Compute stats from this window (not recommended for test sets)
            X_mean = X.mean(axis=0)
            X_std = X.std(axis=0) + 1e-8
            C_mean = C.mean(axis=0)
            C_std = C.std(axis=0) + 1e-8
        else:
            X_mean, X_std, C_mean, C_std = self.normalization_stats

        # Normalize
        X_norm = (X - X_mean) / X_std
        C_norm = (C - C_mean) / C_std

        return X_norm, C_norm

    def __len__(self) -> int:
        """Return number of windows."""
        return len(self.windows)

    def __getitem__(self, idx: int) -> Data:
        """
        Get a single window as PyTorch Geometric Data object.

        Args:
            idx: Window index

        Returns:
            Data object with:
                - x: Node features (measurements) [n_measurement_vars, window_size]
                - c: Conditioning variables [n_conditioning_vars, window_size]
                - edge_index: Fully connected graph edges
                - y: Fault label (0 for all, since we don't have labels)
                - y_future: Future measurements if pred_horizon > 0
        """
        start_idx, end_idx = self.windows[idx]
        history_end = start_idx + self.window_size

        # Extract window data
        window_data = self.data.iloc[start_idx:history_end]

        # Split into measurements and conditioning
        X = window_data.iloc[:, self.measurement_indices].values
        C = window_data.iloc[:, self.conditioning_indices].values

        # Apply normalization if enabled
        if self.normalize:
            X, C = self._normalize_data(X, C)

        # Transpose to [n_vars, window_size] to match original format
        measurements = torch.tensor(X.T, dtype=torch.float32)  # [n_meas, window]
        conditioning = torch.tensor(C.T, dtype=torch.float32)  # [n_cond, window]

        # Create fully connected graph
        edge_index = self._create_fully_connected_graph(self.n_measurement_vars)

        # Create Data object
        data = Data(x=measurements, edge_index=edge_index, c=conditioning)

        # Add future prediction targets if requested
        if self.pred_horizon > 0:
            future_data = self.data.iloc[history_end:end_idx]
            future_X = future_data.iloc[:, self.measurement_indices].values
            if self.normalize and self.normalization_stats is not None:
                X_mean, X_std, _, _ = self.normalization_stats
                future_X = (future_X - X_mean) / X_std
            future_measurements = torch.tensor(future_X.T, dtype=torch.float32)
            data.y_future = future_measurements

        # Add fault label based on explicit fault type list
        FAULT_TYPES = {'slugging', 'air_blockage', 'air_leakage', 'diverted_flow'}
        is_fault = hasattr(self, 'fault_type') and self.fault_type in FAULT_TYPES
        data.y = torch.tensor([1 if is_fault else 0], dtype=torch.long)

        return data

    @staticmethod
    def _create_fully_connected_graph(n_nodes: int) -> torch.Tensor:
        """Create fully connected graph edge index."""
        src = []
        dst = []
        for i in range(n_nodes):
            for j in range(n_nodes):
                src.append(i)
                dst.append(j)
        return torch.tensor([src, dst], dtype=torch.long)


def create_dataloaders(
    data_dir: str,
    train_split: str = 'train',
    val_split: str = 'val',
    test_split: str = 'test',
    window_size: int = 15,
    stride: int = 1,
    batch_size: int = 32,
    pred_horizon: int = 0,
) -> Tuple[PRONTOMergedDataset, PRONTOMergedDataset, PRONTOMergedDataset]:
    """
    Create train, val, and test datasets with proper normalization.

    Args:
        data_dir: Path to 15var_merged directory
        train_split: Training split name
        val_split: Validation split name
        test_split: Test split name
        window_size: Window size for temporal sequences
        stride: Stride for window creation
        batch_size: Batch size (not used, kept for compatibility)
        pred_horizon: Prediction horizon

    Returns:
        (train_dataset, val_dataset, test_dataset)
    """
    # Create training dataset and compute normalization stats
    train_dataset = PRONTOMergedDataset(
        data_dir=data_dir,
        split=train_split,
        window_size=window_size,
        stride=stride,
        normalize=True,
        normalization_stats=None,
        require_stats=False,
        pred_horizon=pred_horizon,
    )

    # Compute normalization stats from training data
    norm_stats = train_dataset.compute_normalization_stats()

    # Create validation dataset with training stats
    val_dataset = PRONTOMergedDataset(
        data_dir=data_dir,
        split=val_split,
        window_size=window_size,
        stride=stride,
        normalize=True,
        normalization_stats=norm_stats,
        require_stats=True,
        pred_horizon=pred_horizon,
    )

    # Create test dataset with training stats
    test_dataset = PRONTOMergedDataset(
        data_dir=data_dir,
        split=test_split,
        window_size=window_size,
        stride=stride,
        normalize=True,
        normalization_stats=norm_stats,
        require_stats=True,
        pred_horizon=pred_horizon,
    )

    return train_dataset, val_dataset, test_dataset
